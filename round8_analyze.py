"""Round-8 tables, plots and verdict (2026-11-06), from runs/round8. Run with Windows Python
(matplotlib):  PYTHONIOENCODING=utf8 python round8_analyze.py
  -> runs/round8/round8_summary.md, round8_results.json, loss_vs_tokens.png, delta_vs_B.png, u_spectrum.png
Hand-written sections (surprises, proposal) come from runs/round8/round8_notes.md and are appended.

Choices fixed before any H2/H2r/CB result was seen:
- Baseline B = B_r8 (the round-5 tiny B recipe rerun; round 5 kept no tB checkpoint). Round-5 tB is a
  reference row only.
- Tokens: "tokens seen" = stable tokens + the 10% decay branch (as round 5). Val loss = val_loss_full of
  the branch (all 4,999,168 val targets). BPB = loss * tokens / (bytes * ln 2) with runs/round8/valbytes.json.
- Delta vs B: paired per seed (arm s_k - B s_k), averaged over the seeds both have.
- Effective-token multiplier: tokens B (mean curve over its seeds) would need to reach the arm's loss,
  log-linear between B's branch losses, end segments extended (* = extrapolated), / the arm's tokens.
- Rerun floor: max over B and H2 of the seed-to-seed |s1 - s0| at the last branch when seed 1 exists for
  them, else 0.005 (the brief's rule).
- Verdict lines (brief 8.8), at the last common branch (1200M stable unless cut):
  H2 not worse      H2 - B <= +max(0.005, floor)
  H2 better         H2 - B < -2 floor on both of 2 seeds
  H2 worse          H2 - B > +2 floor
  classes matter    H2r - H2 > 2 floor, else "any H2 effect is not explained by the k-means clusters"
  CB worth keeping  CB - B < -2 floor on both of 2 seeds
"""
import glob
import json
import math
import os
import re

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "runs", "round8")
R5 = os.path.join(HERE, "runs", "round5")
LABELS = ["B_r8", "H2", "H2r", "CB", "H2w"]
NICE = {"B_r8": "B (B_r8)", "H2": "H2", "H2r": "H2r", "CB": "CB", "H2w": "H2w"}
VB = json.load(open(os.path.join(R, "valbytes.json")))
BPN = VB["bpb_per_nat"]


def jl(p):
    return [json.loads(l) for l in open(p)]


def runs(label, base=R):
    out = {}
    for p in sorted(glob.glob(os.path.join(base, f"wsd_{label}_s[0-9]*.jsonl"))):
        m = re.search(rf"wsd_{re.escape(label)}_s(\d)(_\d+M)?\.jsonl$", p)
        if not m or not os.path.exists(p[:-6] + ".DONE"):
            continue
        recs = jl(p)
        out[int(m.group(1))] = {"branch": {r["stable_tokens"]: (r["tokens"], r["val_loss_full"])
                                           for r in recs if r.get("event") == "branch"},
                                "final": next(r for r in recs if r.get("event") == "final"),
                                "cut": bool(m.group(2))}
    return out


def mean_curve(rs):
    keys = sorted(set.intersection(*[set(v["branch"]) for v in rs.values()])) if rs else []
    return {k: (rs[min(rs)]["branch"][k][0], float(np.mean([v["branch"][k][1] for v in rs.values()]))) for k in keys}


def tokens_for(curve, L):
    pts = sorted(curve.values())
    x = [math.log(t) for t, _ in pts]
    y = [l for _, l in pts]
    for i in range(len(pts) - 1):
        if (y[i] - L) * (y[i + 1] - L) <= 0 and y[i] != y[i + 1]:
            return math.exp(x[i] + (L - y[i]) * (x[i + 1] - x[i]) / (y[i + 1] - y[i])), False
    i = len(pts) - 2 if L < y[-1] else 0
    return math.exp(x[i] + (L - y[i]) * (x[i + 1] - x[i]) / (y[i + 1] - y[i])), True


def load_opt(name):
    p = os.path.join(R, name)
    return json.load(open(p)) if os.path.exists(p) else None


def main():
    RS = {l: runs(l) for l in LABELS}
    RS = {l: v for l, v in RS.items() if v}
    tB5 = runs("tB", R5)
    assert "B_r8" in RS, "B_r8 is not finished"
    B = RS["B_r8"]
    Bc = mean_curve(B)
    stables = sorted(Bc)
    res = {"valbytes": VB, "arms": {}, "notes": []}

    # floor
    spreads = {}
    for l in ("B_r8", "H2"):
        if l in RS and 0 in RS[l] and 1 in RS[l]:
            k = max(set(RS[l][0]["branch"]) & set(RS[l][1]["branch"]))
            spreads[l] = abs(RS[l][1]["branch"][k][1] - RS[l][0]["branch"][k][1])
    floor = max(spreads.values()) if spreads else 0.005
    res["floor"] = {"value": floor, "from": spreads or "default 0.005 (one seed)"}

    def delta(l, s):
        """paired Delta vs B per stable branch, mean over common seeds"""
        seeds = sorted(set(RS[l]) & set(B))
        out = {}
        for k in s:
            ds = [RS[l][sd]["branch"][k][1] - B[sd]["branch"][k][1] for sd in seeds
                  if k in RS[l][sd]["branch"] and k in B[sd]["branch"]]
            if ds:
                out[k] = (float(np.mean(ds)), ds)
        return out

    L = ["# Round 8: LM-head experiments on the tiny proxy (2026-11-06)", "",
         "Generated by `PYTHONIOENCODING=utf8 python round8_analyze.py` (Windows Python) from `runs/round8/`; "
         "method choices are pinned in the script's docstring. Hand-written notes at the end come from "
         "`runs/round8/round8_notes.md`.", "",
         "**Baseline:** B_r8, a rerun of the round-5 tiny B recipe with the final params kept (round 5 saved no tB "
         "checkpoint, and Steps 1-2 need its trained U). **The k-means classes are a bootstrap:** they are built "
         "from B_r8's trained tied embedding, so H2 and CB start with information from a finished B run.", "",
         f"Val set: {VB['rows']} rows x 1024 targets = {VB['tokens']:,} tokens, {VB['bytes']:,} UTF-8 bytes "
         f"({VB['bytes_per_token']:.3f} bytes/token; EOT counted as 0 bytes). BPB = nats x {BPN:.5f}.", ""]

    # ---- 1. branch table
    seeds_of = {l: sorted(v) for l, v in RS.items()}
    L += ["## 1. Val loss per branch", "",
          "Loss in nats/token (BPB in brackets); Δ vs B paired per seed. `c` = cut horizon. Seeds per arm: " +
          ", ".join(f"{NICE[l]} {seeds_of[l]}" for l in RS) + ".", "",
          "| arm | " + " | ".join(f"{k / 1e6:.0f}M" for k in stables) + " |", "|---|" + "---|" * len(stables)]
    if tB5:
        c5 = mean_curve(tB5)
        L.append("| round-5 tB (ref) | " + " | ".join(f"{c5[k][1]:.4f}" if k in c5 else "-" for k in stables) + " |")
        L.append("| B_r8 − round-5 tB | " + " | ".join(f"{Bc[k][1] - c5[k][1]:+.4f}" if k in c5 else "-" for k in stables) + " |")
        res["B_r8_minus_round5_tB"] = {str(k): Bc[k][1] - c5[k][1] for k in stables if k in c5}
    for l in RS:
        c = mean_curve(RS[l])
        cut = any(v["cut"] for v in RS[l].values())
        row = []
        for k in stables:
            row.append(f"{c[k][1]:.4f} ({c[k][1] * BPN:.4f})" + ("c" if cut and k == max(c) else "") if k in c else "-")
        L.append(f"| {NICE[l]} | " + " | ".join(row) + " |")
        res["arms"][l] = {"seeds": seeds_of[l], "cut": cut,
                          "per_seed": {sd: {str(k): v for k, v in RS[l][sd]["branch"].items()} for sd in RS[l]},
                          "mean_loss": {str(k): c[k][1] for k in c}, "mean_bpb": {str(k): c[k][1] * BPN for k in c},
                          "tokens_seen": {str(k): c[k][0] for k in c}}
    for l in RS:
        if l == "B_r8":
            continue
        d = delta(l, stables)
        L.append(f"| Δ {NICE[l]} − B | " + " | ".join(
            (f"{d[k][0]:+.4f}" + (" (" + ", ".join(f"{x:+.4f}" for x in d[k][1]) + ")" if len(d[k][1]) > 1 else ""))
            if k in d else "-" for k in stables) + " |")
        res["arms"][l]["delta_vs_B"] = {str(k): {"mean": v[0], "per_seed": v[1]} for k, v in d.items()}
    L.append("")

    # ---- 2. effective tokens
    L += ["## 2. Effective-token multiplier", "",
          "Tokens B would need to reach the arm's loss, as a multiple of the arm's tokens (log-linear on B's branch "
          "losses; * = extrapolated beyond B's measured range).", "",
          "| arm | " + " | ".join(f"{k / 1e6:.0f}M" for k in stables) + " |", "|---|" + "---|" * len(stables)]
    for l in RS:
        if l == "B_r8":
            continue
        c = mean_curve(RS[l])
        cells, js = [], {}
        for k in stables:
            if k not in c:
                cells.append("-")
                continue
            t, ex = tokens_for(Bc, c[k][1])
            cells.append(f"{t / c[k][0]:.2f}" + ("*" if ex else ""))
            js[str(k)] = {"multiplier": t / c[k][0], "extrapolated": ex}
        L.append(f"| {NICE[l]} | " + " | ".join(cells) + " |")
        res["arms"][l]["token_multiplier"] = js
    L.append("")

    # ---- 2b. early training (paired train loss) and wall-clock matching (added after the results; not brief metrics)
    def train_recs(l, sd=0):
        p = os.path.join(R, f"wsd_{l}_s{sd}.jsonl")
        recs = jl(p)
        t0 = next(r["t"] for r in recs if "t" in r)
        return {r["step"]: (r["tokens"], r["loss"], r["t"] - t0) for r in recs if r.get("event") == "train"}
    TB = train_recs("B_r8")
    L += ["## 2b. Early training and wall-clock matching (seed 0; descriptive, added after the results)", "",
          "Paired train loss (arm − B) at the same steps: identical batches, stable LR, logged every 20 steps; "
          "5-point centred mean (100 steps). 'Crossover' = tokens at the last step where the smoothed difference "
          "is ≤ 0 (arm ahead or tied); after it the arm stays behind B for the whole stable phase. These are train "
          "losses before any decay, so they are not comparable to the branch table in absolute terms.", "",
          "| arm | Δ@100 steps (6.6M) | Δ@200 (13.1M) | Δ@400 (26.2M) | Δ@800 (52.4M) | crossover |", "|---|---|---|---|---|---|"]
    res["early"] = {}
    for l in RS:
        if l == "B_r8" or 0 not in RS[l]:
            continue
        TA = train_recs(l)
        st = sorted(set(TA) & set(TB))
        d = np.array([TA[s][1] - TB[s][1] for s in st])
        sm = np.convolve(d, np.ones(5) / 5, mode="same")
        nonpos = np.where(sm[2:-2] <= 0)[0] + 2
        if len(nonpos) == 0:
            cross = "never ahead"
        elif nonpos.max() >= len(st) - 3:
            cross = "ahead to the end"
        else:
            cross = f"{TB[st[nonpos.max()]][0] / 1e6:.1f}M (step {st[nonpos.max()]})"
        at = {s: float(TA[s][1] - TB[s][1]) for s in (100, 200, 400, 800) if s in TA and s in TB}
        L.append(f"| {NICE[l]} | " + " | ".join(f"{at[s]:+.3f}" if s in at else "-" for s in (100, 200, 400, 800)) + f" | {cross} |")
        res["early"][l] = {"delta_train_at_step": at, "crossover": cross}
    # wall-clock matching: B tokens reached (stable phase, incl. the time its earlier inline branches took) after the
    # arm's full-run wall time; B's decayed loss at that token count, log-linear between B's branch losses
    L += ["", "Wall-clock matching: B's stable-phase tokens reached after the arm's whole-run wall time (B's clock "
          "includes its own earlier inline branches and evals), and B's branch-decayed loss at that many stable tokens "
          "(log-linear in stable tokens between B's branches, i.e. as if B had branched there; the decay steps' "
          "own time is not charged to B). Full-run wall times include machine drift.", "",
          "| arm | arm wall s | arm loss (last branch) | B tokens in that time | B loss there | arm − B |", "|---|---|---|---|---|---|"]
    bpts = sorted((k, v[1]) for k, v in Bc.items())   # keyed by stable tokens, like the train records
    def b_loss_at(tok):
        x = [math.log(t) for t, _ in bpts]
        y = [v for _, v in bpts]
        lt = math.log(tok)
        i = max(0, min(len(x) - 2, int(np.searchsorted(x, lt)) - 1))
        return y[i] + (lt - x[i]) * (y[i + 1] - y[i]) / (x[i + 1] - x[i]), not (x[0] <= lt <= x[-1])
    res["wallclock_match"] = {}
    bt = sorted(TB.values(), key=lambda v: v[2])
    for l in RS:
        if l == "B_r8" or 0 not in RS[l]:
            continue
        w = RS[l][0]["final"]["wall_s"]
        lastk = max(RS[l][0]["branch"])
        la = RS[l][0]["branch"][lastk][1]
        tokB = next((v[0] for v in bt if v[2] >= w), None)
        if tokB is None:   # the arm took longer than B's whole run: B finishes, compare with B's last branch
            tokB, lb, ex = max(Bc), Bc[max(Bc)][1], False
            tb_txt = f"all ({tokB / 1e6:.0f}M; B finished)"
        else:
            lb, ex = b_loss_at(tokB)
            tb_txt = f"{tokB / 1e6:.0f}M"
        L.append(f"| {NICE[l]} | {w:.0f} | {la:.4f} | {tb_txt} | {lb:.4f}{'*' if ex else ''} | {la - lb:+.4f} |")
        res["wallclock_match"][l] = {"arm_wall_s": w, "arm_loss": la, "B_tokens": tokB, "B_loss": lb, "delta": la - lb}
    L.append("")

    # ---- 3. cost table
    G = load_opt("gates.json") or {}
    SM = (load_opt("smoke_check.json") or {}).get("arms", {})
    acct = G.get("accounting", {})
    arm_of = {"B_r8": "tB", "H2": "tH2", "H2r": "tH2r", "CB": "tCB", "H2w": "tH2w"}
    L += ["## 3. Cost per arm", "",
          "Head forward FLOPs/token: B 2·V·d (V = 50,304 incl. 47 pad rows), H2 2·(C + 50)·d, CB 2·50,257·d + 2·C·d, "
          "H2w 2·128·512 + 2·(C + 50)·512. tok/s, step time and VRAM: the 200-step smoke runs, back to back on an "
          "otherwise idle GPU (`r8smoke.sh`); full-run tok/s from each run's final record (includes machine drift).", "",
          "| arm | total params | new params | head fwd FLOPs/tok | × B | train FLOPs/tok | smoke tok/s | × B | step ms | peak VRAM GB | full-run tok/s | wall min |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for l in LABELS:
        a = arm_of[l]
        ac, sm = acct.get(a), SM.get(a)
        if not ac:
            continue
        fin = RS.get(l, {}).get(0, {}).get("final", {})
        L.append(f"| {NICE[l]} | {ac['total_params']:,} | {ac['new_params']:,} | {ac['head_fwd_flops_per_token']:,} | "
                 f"{ac['head_ratio_to_B']:.4f} | {ac['train_flops_per_token']['total']:,} | "
                 + (f"{sm['tok_s']:,.0f} | {sm['speed_vs_tB']:.2f} | {sm['step_ms']:.0f} | {sm['peak_mem_gb']:.2f} | " if sm else "- | - | - | - | ")
                 + (f"{fin['tok_s']:,.0f} | {fin['wall_s'] / 60:.1f} |" if fin else "- | - |"))
        res["arms"].setdefault(l, {})["cost"] = {"accounting": ac, "smoke": sm,
                                                 "full_tok_s": fin.get("tok_s"), "wall_s": fin.get("wall_s"),
                                                 "peak_mem_gb_full": fin.get("peak_mem_gb")}
    L.append("")

    # ---- 3b. parameters per layer and memory (round8_params.py; added after the results)
    PM = load_opt("params_memory.json")
    if PM:
        T = PM["tiny"]
        cols = [("tB", "B"), ("tH2", "H2 / H2r"), ("tCB", "CB"), ("tH2w", "H2w")]
        L += ["## 3b. Parameters per layer and memory", "",
              "Counted from the real init pytree (`JAX_PLATFORMS=cpu python round8_params.py` -> `params_memory.json`). "
              "The 6 blocks are unique (not shared), each followed by its own per-copy norms and alphas. "
              "Count (share of the arm's total).", "",
              "| layer | " + " | ".join(n for _, n in cols) + " |", "|---|" + "---|" * len(cols)]
        def order(g):
            return (0 if g.startswith("embedding") else 1 if g.startswith("block") else 2 if g == "final norm" else 3, g)
        groups = sorted(set().union(*[T[a]["layers"] for a, _ in cols]), key=order)
        for g in groups:
            cells = []
            for a, _ in cols:
                r = T[a]["layers"].get(g)
                cells.append(f"{r['total']:,} ({100 * r['total'] / T[a]['total']:.1f}%)" if r else "-")
            L.append(f"| {g} | " + " | ".join(cells) + " |")
        L.append("| **total** | " + " | ".join(f"**{T[a]['total']:,}**" for a, _ in cols) + " |")
        b0 = T["tB"]["layers"]["block 0"]["parts"]
        L += ["", "Each block: " + ", ".join(f"{k} {v:,}" for k, v in b0.items()) +
              f" = {sum(b0.values()):,}. The 6 blocks together are {6 * sum(b0.values()):,} params, "
              f"{100 * 6 * sum(b0.values()) / T['tB']['total']:.0f}% of B; the tied embedding is "
              f"{100 * T['tB']['layers']['embedding (tied: input + flat output)']['total'] / T['tB']['total']:.0f}%.", ""]
        L += ["Memory. Training state = fp32 params + grads + AdamW m, v (16 B/param); inference weights = bf16 "
              "(2 B/param). Measured peak = the 200-step smoke run (`smoke_check.json`); the rest of the peak is "
              "activations, the head's logits chunks and XLA workspace (micro-batch 16 x 1024 tokens).", "",
              "| arm | params | training state MB | bf16 weights MB | measured train peak GB | peak − state GB |",
              "|---|---|---|---|---|---|"]
        for a, n in [("tB", "B"), ("tH2", "H2"), ("tH2r", "H2r"), ("tCB", "CB"), ("tH2w", "H2w")]:
            r = T[a]
            pk = SM.get(a, {}).get("peak_mem_gb")
            L.append(f"| {n} | {r['total']:,} | {r['train_state_MB']:.1f} | {r['inference_bf16_MB']:.1f} | "
                     + (f"{pk:.2f} | {pk - r['train_state_MB'] / 1e3:.2f}" if pk else "- | -") + " |")
        Bg = PM["big_600M"]
        fl, hi = Bg["flat"], Bg["two-level C=1024"]
        pl = fl["per_layer"]
        L += ["", "600M decode config (Step 7; analytic, `round8_params.py`): 28 layers x d1280, GQA 20/4 (hd 64), "
              "SwiGLU 3456, tied V = 65,536.", "",
              "| | flat head | two-level head (C = 1024) |", "|---|---|---|",
              f"| per layer: attention / FFN / norms | {pl['attention']:,} / {pl['FFN (SwiGLU)']:,} / {pl['norms']:,} | same |",
              f"| per layer total (x 28) | {pl['total']:,} ({28 * pl['total']:,}) | same |",
              f"| tied embedding | {fl['embedding (tied)']:,} ({100 * fl['embedding (tied)'] / fl['total']:.1f}%) | same |",
              f"| head extra (Vc + bc) | 0 | {hi['head extra']:,} |",
              f"| total | {fl['total']:,} | {hi['total']:,} |",
              f"| bf16 weights MB | {fl['inference_bf16_MB']:.1f} | {hi['inference_bf16_MB']:.1f} |",
              f"| training state MB (16 B/param) | {fl['train_state_MB']:.0f} | {hi['train_state_MB']:.0f} |",
              f"| head weights read per decoded token, MB (bf16) | {fl['head_weights_read_per_token_MB_bf16']:.2f} | "
              f"{hi['head_weights_read_per_token_MB_bf16']:.2f} |",
              f"| KV cache per 1k tokens of context, MB (bf16) | {fl['kv_cache_MB_per_1k_tokens_bf16']:.1f} | same |", ""]
        res["params_memory"] = PM

    # ---- 4. diagnostics
    D = {t: load_opt(f"diag_{t}.json") for t in ("B", "H2")}
    CR = load_opt("classes_report.json")
    L += ["## 4. Diagnostics (Step 1) and classes (Step 2)", ""]
    if CR:
        L += [f"Classes: balanced_kmeans(U_B[:50257], C = {CR['C']}), capacity {CR['capacity']}; k-means sizes "
              f"min/median/max {CR['kmeans_sizes']['min']}/{CR['kmeans_sizes']['median']:.0f}/{CR['kmeans_sizes']['max']} "
              f"({CR['kmeans_sizes']['n_full']} classes full); random control min/median/max "
              f"{CR['random_sizes']['min']}/{CR['random_sizes']['median']:.0f}/{CR['random_sizes']['max']} "
              f"(same histogram: {CR['same_histogram']}). Decoded example classes: `runs/round8/classes_examples.txt`.", ""]
        res["classes"] = CR
    if any(D.values()):
        L += ["grad_retention = share of ‖p − y‖² inside the logit directions the backbone can move, 64 val batches of "
              "256 positions; mean ± std over batches. 'chance' = basis dims / V (a random residual's share).", "",
              "| model | flat col([U,1]) | with classes col([U,S,1]) | chance flat / classes | U σ top-5 | spectral entropy (eff. rank) |",
              "|---|---|---|---|---|---|"]
        for t, d in D.items():
            if not d:
                continue
            L.append(f"| {t} final ({d['ckpt']}) | {d['grad_retention_flat']['mean']:.4f} ± {d['grad_retention_flat']['std']:.4f} | "
                     f"{d['grad_retention_with_classes']['mean']:.4f} ± {d['grad_retention_with_classes']['std']:.4f} | "
                     f"{d['chance_share']['flat']:.4f} / {d['chance_share']['with_classes']:.4f} | "
                     + ", ".join(f"{x:.2f}" for x in d["U_top5"]) + f" | {d['U_spectral_entropy']:.3f} ({d['U_effective_rank']:.1f}) |")
            res.setdefault("diagnostics", {})[t] = {k: v for k, v in d.items() if k not in ("per_batch", "U_singular_values")}
        L.append("")

    # ---- 5. decode
    if os.path.exists(os.path.join(R, "decode.md")):
        L += ["## 5. Decode benchmark (Step 7)", "", "From `runs/round8/decode.md`:", ""]
        L += [("#" + l if l.startswith("## ") else l)
              for l in open(os.path.join(R, "decode.md"), encoding="utf8").read().split("\n")[2:]]
        res["decode"] = jl(os.path.join(R, "decode.jsonl"))
        fb = load_opt("decode_fallback.json")
        if fb:
            res["decode_fallback_trained"] = fb

    # ---- 6. verdict
    common = [k for k in stables if all(k in mean_curve(RS[l]) for l in RS if l in ("B_r8", "H2", "H2r", "CB"))]
    last = max(common) if common else max(stables)
    V = []

    def dd(l):
        return delta(l, [last]).get(last) if l in RS else None
    h2, h2r, cb = dd("H2"), dd("H2r"), dd("CB")
    tol = max(0.005, floor)
    if h2:
        two = len(h2[1]) >= 2
